class BrainError(Exception):
    """A canonical-source problem that stops generation before anything is written."""


@dataclass(frozen=True)
class Out:
    """One generated file; `mode` carries the permission bits of a copied canonical file."""
    data: bytes
    mode: int | None = None


@dataclass
class Render:
    """The expected state of every generated path, built in memory."""
    files: dict[str, Out] = field(default_factory=dict)
    dirs: set[str] = field(default_factory=lambda: set(OWNED_DIRS))


# --------------------------------------------------------------------------- generation
@dataclass(frozen=True)
class Entity:
    """One canonical agent or skill: its frontmatter, and the body bytes that follow it."""
    meta: dict
    body: bytes
    path: Path


def strict_yaml_load(text: str, rel: str) -> object:
    """yaml.safe_load, except that a repeated mapping key is a BrainError naming `rel`.

    safe_load keeps the last of a repeated key, so a second `allowed-tools:` in
    frontmatter, or a second `claude:` in a permission entry, would silently win.
    """
    import yaml  # PyYAML, a declared dependency of brain.py

    class StrictLoader(yaml.SafeLoader):
        def construct_mapping(self, node, deep=False):
            seen: set[str] = set()
            for key in (k for k, _ in node.value if isinstance(k, yaml.ScalarNode)):
                if key.value in seen:
                    raise BrainError(f"{rel}: duplicate key `{key.value}`")
                seen.add(key.value)
            return super().construct_mapping(node, deep)
    return yaml.load(text, Loader=StrictLoader)  # noqa: S506 (a SafeLoader)


def split_frontmatter(raw: bytes, rel: str) -> tuple[dict, bytes]:
    """(metadata, body): the leading `---` block, and what follows it minus one blank line."""
    try:
        import yaml  # PyYAML, a declared dependency of brain.py
    except ImportError:
        raise BrainError("PyYAML is required to parse frontmatter: pip install pyyaml") from None
    end = raw.find(b"\n---\n", 3) if raw.startswith(b"---\n") else -1
    if end < 0:
        raise BrainError(f"{rel}: no YAML frontmatter; the file must open with a `---` block that "
                         "carries its metadata (there are no defaults).")

    try:
        data = strict_yaml_load(raw[4:end + 1].decode("utf-8"), rel)
    except (UnicodeDecodeError, yaml.YAMLError) as exc:
        raise BrainError(f"{rel}: frontmatter is not valid YAML ({' '.join(str(exc).split())}).") from exc
    if not isinstance(data, dict):
        raise BrainError(f"{rel}: frontmatter is not a YAML mapping.")
    body = raw[end + 5:]
    return data, body[1:] if body.startswith(b"\n") else body


def validate(data: dict, schema: dict, where: str, prefix: str = "") -> list[str]:
    """Problems with `data` against `schema`: unknown, missing, empty, or invalid keys."""
    problems = [f"{where}: unknown key `{prefix}{key}` (allowed: {', '.join(schema)})."
                for key in data if key not in schema]
    for key, (required, rule) in schema.items():
        label, value = f"`{prefix}{key}`", data.get(key)
        if key not in data:
            if required:
                problems.append(f"{where}: required key {label} is missing; there are no defaults.")
        elif isinstance(rule, dict):
            problems += (validate(value, rule, where, f"{prefix}{key}.") if isinstance(value, dict)
                         else [f"{where}: {label} must be a mapping."])
        elif rule == "bool":
            if not isinstance(value, bool):
                problems.append(f"{where}: {label} must be true or false.")
        elif rule == "hooks":
            problems += validate_hooks(value, where, label)
        elif rule == "globs":
            if not isinstance(value, list) or not value or not all(
                    isinstance(v, str) and v.strip() and "\n" not in v for v in value):
                problems.append(f"{where}: {label} must be a non-empty list of glob strings.")
        elif rule == "list":
            if not isinstance(value, list) or not value or not all(
                    isinstance(v, str) and v.strip() and not {",", "\n"} & set(v) for v in value):
                problems.append(f"{where}: {label} must be a non-empty list of strings without commas.")
        elif not isinstance(value, str) or not value.strip() or "\n" in value:
            problems.append(f"{where}: {label} must be a non-empty single-line string; omit an optional "
                            "key to inherit.")
        elif isinstance(rule, set) and value not in rule:
            problems.append(f"{where}: {label} has invalid value '{value}' (allowed: {', '.join(sorted(rule))}).")
        elif isinstance(rule, re.Pattern) and not rule.fullmatch(value):
            problems.append(f"{where}: {label} has invalid value '{value}' (allowed: {rule.pattern}).")
    return problems


def validate_hooks(value: object, where: str, label: str) -> list[str]:
    """Problems with an agent's `hooks:` mapping: known events, each a list of single hooks."""
    if not isinstance(value, dict) or not value:
        return [f"{where}: {label} must be a mapping of hook events ({', '.join(HOOK_EVENTS)})."]
    problems: list[str] = []
    for event, entries in value.items():
        if event not in HOOK_EVENTS:
            problems.append(f"{where}: {label} has unknown event `{event}` (allowed: {', '.join(HOOK_EVENTS)}).")
            continue
        if not isinstance(entries, list) or not entries:
            problems.append(f"{where}: {label}.{event} must be a non-empty list of hooks.")
            continue
        for index, entry in enumerate(entries):
            at = f"{label}.{event}[{index}]"
            if not isinstance(entry, dict):
                problems.append(f"{where}: {at} must be a mapping with `command`.")
                continue
            problems += [f"{where}: {at} has unknown key `{k}` (allowed: {', '.join(sorted(HOOK_KEYS))})."
                         for k in entry if k not in HOOK_KEYS]
            for key, needed in (("command", True), ("matcher", HOOK_EVENTS[event])):
                text = entry.get(key)
                if (needed or key in entry) and (not isinstance(text, str) or not text.strip() or "\n" in text):
                    problems.append(f"{where}: {at}.{key} must be a non-empty single-line string.")
            timeout = entry.get("timeout", 1)
            if isinstance(timeout, bool) or not isinstance(timeout, int) or timeout < 1:
                problems.append(f"{where}: {at}.timeout must be a positive whole number of seconds.")
    return problems


def claude_hooks(hooks: dict) -> dict:
    """The Claude settings form of a canonical `hooks:` mapping: each entry wraps one command hook."""
    return {event: [{**({"matcher": e["matcher"]} if "matcher" in e else {}),
                     "hooks": [{"type": "command", "command": e["command"],
                                **({"timeout": e["timeout"]} if "timeout" in e else {})}]}
                    for e in entries] for event, entries in hooks.items()}


def hooks_lines(hooks: dict) -> list[str]:
    """`claude_hooks()` as YAML frontmatter lines, strings double-quoted and escaped."""
    lines = ["hooks:"]
    for event, entries in claude_hooks(hooks).items():
        lines.append(f"  {event}:")
        for entry in entries:
            lead = "    - "
            if "matcher" in entry:
                lines.append(f'{lead}matcher: "{escape(entry["matcher"])}"')
                lead = "      "
            lines.append(f"{lead}hooks:")
            for hook in entry["hooks"]:
                lines.append(f"        - type: {hook['type']}")
                lines.append(f'          command: "{escape(hook["command"])}"')
                if "timeout" in hook:
                    lines.append(f"          timeout: {hook['timeout']}")
    return lines


def descriptions(meta: dict) -> list[str]:
    """The entity's description, plus the Codex override an agent may carry."""
    codex = meta.get("codex") if isinstance(meta.get("codex"), dict) else {}
    return [d for d in (meta.get("description"), codex.get("description")) if isinstance(d, str)]


def load_entities(infra: Path) -> tuple[dict[tuple[str, str], Entity], list[str]]:
    """(kind, name) -> Entity for every canonical agent, skill, and rule, and every frontmatter problem."""
    entities: dict[tuple[str, str], Entity] = {}
    problems: list[str] = []
    for kind, (sub, schema) in SCHEMAS.items():
        directory, flat = infra / sub, kind in ("agent", "rule")
        for name in [n[:-3] for n in md_names(directory)] if flat else skill_names(directory):
            path = directory / name / "SKILL.md"  # a structured skill wins over a flat file
            path = path if not flat and path.is_file() else directory / f"{name}.md"
            rel = path.relative_to(infra.parent).as_posix()
            try:
                meta, body = split_frontmatter(path.read_bytes(), rel)
            except BrainError as exc:
                problems.append(str(exc))
                continue
            problems += validate(meta, schema, rel)
            if kind == "rule" and ("paths" in meta) != (meta.get("load") == "paths"):
                problems.append(f"{rel}: `paths:` goes with `load: paths` and only with it; a `paths:` key on "
                                "another tier would never load the rule, and `load: paths` needs the globs.")
            if isinstance(meta.get("name"), str) and meta["name"] != name:
                problems.append(f"{rel}: name '{meta['name']}' does not match the file or directory name.")
            problems += [f"{rel}: a description is {len(d)} characters; the limit is {MAX_DESCRIPTION}."
                         for d in descriptions(meta) if len(d) > MAX_DESCRIPTION]
            entities[(kind, name)] = Entity(meta, body, path)
    return entities, problems


def escape(value: str) -> str:
    """Escape for a YAML or TOML double-quoted string: backslashes first, then quotes."""
    return value.replace("\\", "\\\\").replace('"', '\\"')


def yaml_list(items: list[str]) -> str:
    """`[Read, Bash(x *)]` -> `["Read", "Bash(x *)"]`, each item trimmed of spaces."""
    return "[" + ", ".join(f'"{escape(t.strip(" "))}"' for t in items) + "]"


def read_source(path: Path, label: str) -> bytes:
    if not path.is_file():
        raise BrainError(f"Missing canonical {label}: {path}")
    return path.read_bytes()


def mode_of(path: Path) -> int:
    return stat.S_IMODE(path.stat().st_mode)


def md_names(directory: Path) -> list[str]:
    """Top-level `*.md` files except README.md. Parity: `find -type f` skips symlinks."""
    if not directory.is_dir():
        raise BrainError(f"Missing directory: {directory}")
    return sorted(e.name for e in directory.iterdir() if e.name.endswith(".md")
                  and e.name != "README.md" and e.is_file() and not e.is_symlink())


def skill_names(directory: Path) -> list[str]:
    """Skills in flat (`<n>.md`) or structured (`<n>/SKILL.md`) layout."""
    names = {n[:-3] for n in md_names(directory)}
    names |= {e.name for e in directory.iterdir() if e.is_dir() and not e.is_symlink()
              and (e / "SKILL.md").is_file() and not (e / "SKILL.md").is_symlink()}
    return sorted(names)


def copy_subtree(src: Path, dest: str, out: Render) -> None:
    """Parity: `cp -R` plus copy_tree keep real files and directories only, minus .DS_Store."""
    out.dirs.add(dest)
    for entry in sorted(src.iterdir()):
        if entry.is_symlink():
            continue
        if entry.is_dir():
            copy_subtree(entry, f"{dest}/{entry.name}", out)
        elif entry.is_file() and entry.name != ".DS_Store":
            out.files[f"{dest}/{entry.name}"] = Out(entry.read_bytes(), mode_of(entry))


def splice(body: bytes, invocation: str) -> bytes:
    """Put invocation text under the first `## Input` line, else append that section.

    Parity: the awk splice ends every line with a newline, including a body's unterminated
    last line.
    """
    lines = body.split(b"\n")
    if lines[-1] == b"":
        lines.pop()
    text = invocation.encode().split(b"\n")[:-1]
    if b"## Input" in lines:
        at = lines.index(b"## Input") + 1
        lines[at:at] = [b"", *text]
    else:
        lines += [b"", b"## Input", b"", *text]
    return b"".join(line + b"\n" for line in lines)


def frontmatter(*lines: str) -> bytes:
    return ("---\n" + "".join(line + "\n" for line in lines) + "---\n\n").encode()


def codex_skill_frontmatter(name: str, description: str) -> bytes:
    return frontmatter(f"name: {name}", "description: >-", f"  {description}")


def emit_skill(out: Render, out_dir: str, src_dir: Path, name: str, head: bytes, body: bytes,
               invocation: str | None = None) -> None:
    """One skill bundle: the whole canonical subtree when structured, else only SKILL.md."""
    source = src_dir / name / "SKILL.md"
    structured = source.is_file()  # preferred over a flat file of the same name
    body = splice(body, invocation) if invocation is not None else body
    if structured:
        copy_subtree(source.parent, f"{out_dir}/{name}", out)
    out.dirs.add(f"{out_dir}/{name}")
    out.files[f"{out_dir}/{name}/SKILL.md"] = Out(head + body, mode_of(source) if structured else None)


def render(root: Path) -> Render:
    """Build every generated file in memory; raise BrainError before anything is written."""
    infra = root / "Infrastructure"
    configs = infra / "adapter_configs"
    workflows, style = infra / "skills", infra / "style" / "skills"
    duplicates = sorted(set(skill_names(workflows)) & set(skill_names(style)))
    if duplicates:
        raise BrainError(f"Duplicate generated skill names detected: {', '.join(duplicates)}")
    entities, problems = load_entities(infra)
    if problems:
        raise BrainError("invalid canonical frontmatter:\n" + "".join(f"  {p}\n" for p in problems))
    out = Render()

    # Bodies are copied as written: they cite Infrastructure/ paths, which both adapters read.
    for base in md_names(infra / "agents"):
        name = base[:-3]
        meta, codex = entities[("agent", name)].meta, entities[("agent", name)].meta["codex"]
        out.files[f".claude/agents/{base}"] = Out(frontmatter(
            f"name: {name}", f'description: "{escape(meta["description"])}"', f"tools: {','.join(meta['tools'])}",
            *(f"{key}: {meta[key]}" for key in ("model", "effort") if key in meta),
            *(hooks_lines(meta["hooks"]) if "hooks" in meta else [])) + entities[("agent", name)].body)
        toml = [f'name = "{escape(name)}"',
                f'description = "{escape(codex.get("description", meta["description"]))}"',
                *(f'{key} = "{escape(codex[col])}"' for key, col in
                  (("model", "model"), ("model_reasoning_effort", "reasoning_effort")) if col in codex),
                f'sandbox_mode = "{escape(codex["sandbox_mode"])}"']
        out.files[f".codex/agents/{name}.toml"] = Out(
            ("\n".join(toml) + "\n" + CODEX_AGENT_BODY.format(base=base)).encode())
    for base in md_names(infra / "rules"):
        rule = entities[("rule", base[:-3])]
        if rule.meta["load"] in MIRRORED_LOADS:  # `load:` is brain.py's; Claude reads only `paths:`
            globs = "".join(f'  - "{escape(glob)}"\n' for glob in rule.meta.get("paths", []))
            out.files[f".claude/rules/{base}"] = Out(
                (frontmatter("paths:" + ("\n" + globs).rstrip("\n")) if globs else b"") + rule.body)

    for name in skill_names(workflows):
        meta, body = entities[("workflow", name)].meta, entities[("workflow", name)].body
        hint = meta.get("argument-hint")
        head = [f"name: {name}", f'description: "{escape(meta["description"])}"']
        if hint:
            head.append(f'argument-hint: "{escape(hint)}"')
            invocation = f"Invoke as `/{name} {hint}`.\n\nArguments: $ARGUMENTS\n"
        else:
            invocation = f"Invoke as `/{name}`. It takes no arguments.\n"
        head.append(f"allowed-tools: {yaml_list(meta['allowed-tools'])}")
        if "disable-model-invocation" in meta:
            head.append(f"disable-model-invocation: {str(meta['disable-model-invocation']).lower()}")
        emit_skill(out, ".claude/skills", workflows, name, frontmatter(*head), body, invocation)
        emit_skill(out, ".agents/skills", workflows, name, codex_skill_frontmatter(name, meta["description"]),
                   body, f"Mention `${name}` with the details in the same message, pick the skill by name, "
                   "or simply describe the task. Treat the invoking message as this workflow input.\n")
    for name in skill_names(style):
        meta, body = entities[("skill", name)].meta, entities[("skill", name)].body
        emit_skill(out, ".claude/skills", style, name, frontmatter(
            f"name: {name}", f'description: "{escape(meta["description"])}"',
            f'argument-hint: "{escape(meta["argument-hint"])}"',
            f"allowed-tools: {yaml_list(meta['allowed-tools'])}"), body)
        emit_skill(out, ".agents/skills", style, name, codex_skill_frontmatter(name, meta["description"]), body)

    # The root AGENTS.md and CLAUDE.md are written by hand (lint_canonical checks them).
    for dest, src in ((".codex/hooks.json", configs / "codex.hooks.json"),
                      (".codex/config.toml", configs / "codex.config.toml"),
                      (".claude/README.md", configs / "claude.README.md"),
                      (".codex/README.md", configs / "codex.README.md")):
        out.files[dest] = Out(read_source(src, "adapter source"), mode_of(src))
    settings, execpolicy = render_policy(configs)
    out.files[".claude/settings.json"], out.files[".codex/rules/template.rules"] = Out(settings), Out(execpolicy)
    out.files[MANIFEST] = Out(manifest_bytes(out.files))
    return out


# --------------------------------------------------------------------------- permission policy
# One command policy (adapter_configs/permissions.yaml) renders Claude's `permissions` and the
# Codex execpolicy. A decision maps to a Claude list; Codex takes only `prompt` and `forbidden`,
# because an execpolicy `allow` runs its command unsandboxed and without a prompt.
POLICY = "permissions.yaml"
CLAUDE_LISTS = {"allow": "allow", "prompt": "ask", "forbidden": "deny"}
POLICY_KEYS = {"decision", "reason", "note", "claude", "codex"}
CODEX_KEYS = ("pattern", "match", "not_match")
EXAMPLE_WIDTH = 100  # a Codex example list longer than this goes one item per line


def strings(value: object, nested: bool = False) -> bool:
    """A non-empty list of non-empty single-line strings (or, when `nested`, of such lists)."""
    return isinstance(value, list) and bool(value) and all(
        strings(v) if nested and isinstance(v, list) else isinstance(v, str) and bool(v.strip()) and "\n" not in v
        for v in value)


def load_policy(configs: Path) -> tuple[str, list[dict]]:
    """(the Codex header, the policy entries), or BrainError listing every problem."""
    import yaml  # PyYAML; split_frontmatter has already required it
    try:
        data = strict_yaml_load(read_source(configs / POLICY, "permission policy").decode("utf-8"), POLICY)
    except (UnicodeDecodeError, yaml.YAMLError) as exc:
        raise BrainError(f"{POLICY} is not valid YAML ({' '.join(str(exc).split())}).") from exc
    if not isinstance(data, dict) or set(data) != {"codex_header", "policy"} or not isinstance(
            data["codex_header"], str) or not isinstance(data["policy"], list):
        raise BrainError(f"{POLICY} must hold exactly `codex_header` (text) and `policy` (a list).")
    problems: list[str] = []
    for number, entry in enumerate(data["policy"], 1):
        where = f"{POLICY} entry {number}"
        if not isinstance(entry, dict):
            problems.append(f"{where} is not a mapping.")
            continue
        decision = entry.get("decision")
        problems += [f"{where}: unknown key `{key}` (allowed: {', '.join(sorted(POLICY_KEYS))})."
                     for key in entry if key not in POLICY_KEYS]
        if decision not in CLAUDE_LISTS:
            problems.append(f"{where}: `decision` must be one of {', '.join(CLAUDE_LISTS)}.")
        if not entry.get("claude") and not entry.get("codex"):
            problems.append(f"{where} lists no `claude` or `codex` rule.")
        if "claude" in entry and not strings(entry["claude"]):
            problems.append(f"{where}: `claude` must be a non-empty list of permission rules.")
        if "note" in entry and not (isinstance(entry["note"], str) and entry["note"].strip()):
            problems.append(f"{where}: `note` must be text.")
        if "codex" not in entry:
            continue
        if decision == "allow":
            problems.append(f"{where}: Codex takes no `allow` rule, which would run the command unsandboxed "
                            "and without a prompt; drop `codex`, or use prompt or forbidden.")
        if not (isinstance(entry.get("reason"), str) and entry["reason"].strip() and "\n" not in entry["reason"]):
            problems.append(f"{where}: a Codex rule needs a one-line `reason` (its justification).")
        for rule in entry["codex"] if isinstance(entry["codex"], list) and entry["codex"] else [None]:
            if not isinstance(rule, dict) or set(rule) != set(CODEX_KEYS) or not strings(rule["pattern"], True) \
                    or not strings(rule["match"]) or not strings(rule["not_match"]):
                problems.append(f"{where}: each `codex` rule needs exactly a `pattern` (words, or lists of "
                                "alternative words) and non-empty `match` and `not_match` example lists.")
    if problems:
        raise BrainError("invalid permission policy:\n" + "".join(f"  {p}\n" for p in problems))
    return data["codex_header"], data["policy"]


def comment(text: str) -> list[str]:
    return [f"# {line}".rstrip() for line in text.rstrip("\n").split("\n")]


def render_policy(configs: Path) -> tuple[bytes, bytes]:
    """(.claude/settings.json, .codex/rules/template.rules) from the policy and claude.settings.json."""
    header, policy = load_policy(configs)
    def unique(pairs: list[tuple[str, object]]) -> dict:
        """json.loads keeps the last of a repeated key; a second `hooks` must not win."""
        seen: dict = {}
        for key, value in pairs:
            if key in seen:
                raise BrainError(f"claude.settings.json: duplicate key `{key}`")
            seen[key] = value
        return seen
    try:
        base = json.loads(read_source(configs / "claude.settings.json", "adapter source"),
                          object_pairs_hook=unique)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise BrainError(f"claude.settings.json is not valid JSON ({exc}).") from exc
    if not isinstance(base, dict) or "permissions" in base:
        raise BrainError(f"claude.settings.json must be a JSON object without `permissions`, which {POLICY} "
                         "renders.")
    lists = {key: [rule for entry in policy if entry["decision"] == decision for rule in entry.get("claude", [])]
             for decision, key in CLAUDE_LISTS.items()}
    settings = {"permissions": {key: rules for key, rules in lists.items() if rules}, **base}
    lines = comment(header)
    for entry in (e for e in policy if e.get("codex")):
        lines += ["", *comment(entry["note"])] if entry.get("note") else [""]
        for index, rule in enumerate(entry["codex"]):
            examples = []
            for key in ("match", "not_match"):
                one = f"    {key} = {json.dumps(rule[key], ensure_ascii=False)},"
                examples += [one] if len(one) <= EXAMPLE_WIDTH else [
                    f"    {key} = [", *(f"        {json.dumps(x, ensure_ascii=False)}," for x in rule[key]), "    ],"]
            lines += [""] * bool(index) + [
                "prefix_rule(", f"    pattern = {json.dumps(rule['pattern'], ensure_ascii=False)},",
                f'    decision = "{entry["decision"]}",',
                f"    justification = {json.dumps(entry['reason'], ensure_ascii=False)},", *examples, ")"]
    return ((json.dumps(settings, indent=2, ensure_ascii=False) + "\n").encode(),
            ("\n".join(lines) + "\n").encode())


def manifest_bytes(files: dict[str, Out]) -> bytes:
    """The manifest for a generated set: header, note, then every path (itself included)."""
    paths = sorted({*files, MANIFEST})
    bad = [p for p in paths if not p or "\n" in p or "\r" in p or p.startswith("#")]
    if bad:
        raise BrainError(f"Generated path cannot be recorded in {MANIFEST}: {bad[0]!r}")
    return (MANIFEST_HEADER + "\n" + MANIFEST_NOTE + "".join(p + "\n" for p in paths)).encode()


# --------------------------------------------------------------------------- sync
def read_manifest(root: Path) -> set[str] | None:
    """The paths the last sync recorded, or None when there is no readable manifest."""
    try:
        lines = (root / MANIFEST).read_bytes().decode("utf-8").split("\n")
    except (OSError, UnicodeDecodeError):
        return None
    if lines[0] != MANIFEST_HEADER:
        return None
    return {line for line in lines[1:] if line and not line.startswith("#")}


NEVER_DELETED = (".claude/settings.local.json", ".claude/settings.local.json.bak")  # personal settings


def deletable(root: Path, rel: str) -> bool:
    """True for a plain relative path inside an adapter tree, reached through real directories.

    A stale manifest path anywhere else is left in place: a canonical source a hand-edited
    manifest names, a root file such as AGENTS.md that stopped being generated because it is
    now written by hand, a nested worktree, or personal settings. A symlinked directory on the
    way (a committed `.claude/link -> ../data/raw`, or an alias for `.claude/worktrees`) would
    send the deletion outside the adapter tree, so any symlink between the root and the file
    keeps it too. Names compare case-insensitively, as they resolve on macOS.
    """
    parts, folded = rel.split("/"), rel.casefold()
    if not (len(parts) > 1 and parts[0] in ADAPTER_ROOTS and posixpath.normpath(rel) == rel):
        return False
    if any(folded == u.casefold() or folded.startswith(u.casefold() + "/") for u in UNSCANNED):
        return False
    if folded in {n.casefold() for n in NEVER_DELETED}:
        return False
    if any(root.joinpath(*parts[:depth]).is_symlink() for depth in range(1, len(parts))):
        return False
    return (root / rel).parent.resolve() == root.resolve().joinpath(*parts[:-1])


def conflicts(root: Path, expected: Render) -> list[str]:
    """Generated locations that sync cannot write without touching something it does not own.

    A symlinked directory would send generated files outside the repository, and a file or
    directory where the other is needed would have to be deleted; sync refuses both.
    """
    found: set[str] = set()
    dirs = set(expected.dirs) | {rel.rsplit("/", 1)[0] for rel in expected.files if "/" in rel}
    for directory in dirs:
        parts = directory.split("/")
        for depth in range(1, len(parts) + 1):
            prefix, path = "/".join(parts[:depth]), root.joinpath(*parts[:depth])
            if path.is_symlink():
                found.add(f"{prefix} is a symbolic link; sync writes only into real directories.")
                break
            if path.exists() and not path.is_dir():
                found.add(f"{prefix} is a file where sync needs a directory.")
                break
    found |= {f"{rel} is a directory where sync writes a generated file." for rel in expected.files
              if (root / rel).is_dir() and not (root / rel).is_symlink()}
    return sorted(found)


def write(root: Path, rel: str, out: Out, umask: int) -> None:
    """Write one generated file; a symlink in its place is replaced, never followed."""
    path = root / rel
    if path.is_symlink():
        path.unlink()
    is_new = not path.exists()
    path.parent.mkdir(parents=True, exist_ok=True)
    if is_new or path.read_bytes() != out.data:
        path.write_bytes(out.data)
    # Parity: a new file takes its canonical mode, and `cp` onto an existing file keeps that
    # file's mode, except in OWNED_DIRS, which the Bash generator recreated on every sync.
    if out.mode is not None and (is_new or any(rel.startswith(d + "/") for d in OWNED_DIRS)):
        if mode_of(path) != out.mode & ~umask:
            path.chmod(out.mode & ~umask)


def prune(root: Path, directory: Path, keep: set[str]) -> None:
    """Remove the directories a deletion left empty, stopping at the adapter tree root."""
    while directory != root and directory.relative_to(root).as_posix() not in keep:
        try:
            directory.rmdir()  # fails, and stops the walk, unless the directory is empty
        except OSError:
            return
        directory = directory.parent


def listing(paths: list[str]) -> str:
    return "".join(f"  {path}\n" for path in paths)


def sync(root: Path) -> int:
    expected = render(root)
    blocked = conflicts(root, expected)
    if blocked:
        sys.stderr.write(f"Refusing to sync; nothing was changed:\n{listing(blocked)}"
                         "Replace each symbolic link or file with a real directory, and move each "
                         "directory away from a generated file's path, then rerun `make brain-sync`.\n")
        return 1
    previous = read_manifest(root)
    umask = os.umask(0)
    os.umask(umask)
    for directory in sorted(expected.dirs):
        (root / directory).mkdir(parents=True, exist_ok=True)
    for rel, out in sorted(expected.files.items()):
        if rel != MANIFEST:  # written last, so an interrupted sync still knows the old paths
            write(root, rel, out, umask)
    removed: list[str] = []
    kept: list[str] = []
    keep = {*ADAPTER_ROOTS, *expected.dirs}
    for rel in sorted((previous or set()) - set(expected.files)):
        path = root / rel
        if not (path.exists() or path.is_symlink()):
            continue
        if not deletable(root, rel) or (path.is_dir() and not path.is_symlink()):
            kept.append(rel)
            continue
        path.unlink()
        removed.append(rel)
        prune(root, path.parent, keep)
    write(root, MANIFEST, expected.files[MANIFEST], umask)

    print("Generated copies refreshed in .claude/, .codex/ native surfaces, .agents/skills/, "
          ".claude/README.md, .codex/README.md, .claude/settings.json, .codex/config.toml, "
          f".codex/hooks.json, and .codex/rules/; ownership recorded in {MANIFEST}.")
    if previous is None:
        print(f"No previous {MANIFEST} was found, so nothing was deleted. `brain.py check` lists "
              "any file left over from an earlier generation as unowned.")
    if removed:
        print(f"Deleted {len(removed)} file(s) that the previous manifest listed and sync no longer "
              f"generates:\n{listing(removed)}", end="")
    if kept:
        sys.stderr.write(f"Left in place {len(kept)} path(s) the previous manifest listed that are no longer "
                         "generated; sync deletes only files inside .claude/, .codex/, and .agents/, "
                         "reached without a symbolic link, outside .claude/worktrees/, and never "
                         "settings.local.json:\n"
                         f"{listing(kept)}")
    retired = [f"{d}/" for d in RETIRED_DIRS if (root / d).exists() or (root / d).is_symlink()]
    if retired:
        sys.stderr.write(f"Retired Codex surfaces remain; sync deletes only manifest paths, so remove them "
                         f"by hand (`brain.py check` fails until they are gone):\n{listing(retired)}")
    return 0


# --------------------------------------------------------------------------- check: drift
def unowned(root: Path, expected: Render) -> list[str]:
    """Files, links, and empty directories in the adapter trees that sync does not generate."""
    generated_dirs = set(expected.dirs) | {rel.rsplit("/", 1)[0] for rel in expected.files if "/" in rel}
    found: list[str] = []
    for top in ADAPTER_ROOTS:
        if not (root / top).is_dir() or (root / top).is_symlink():
            continue
        for current, dirnames, filenames in os.walk(root / top):  # symlinked dirs are not entered
            base = Path(current).relative_to(root).as_posix()
            dirnames[:] = [d for d in dirnames if f"{base}/{d}" not in UNSCANNED]
            found += [f"{base}/{d}" for d in dirnames if (Path(current) / d).is_symlink()]
            found += [f"{base}/{name}" for name in filenames
                      if name != ".DS_Store" and f"{base}/{name}" not in expected.files]
            if not dirnames and not filenames and base not in generated_dirs:
                found.append(f"{base}/")
    return sorted(found)


def check_drift(root: Path, expected: Render) -> tuple[list[str], list[str]]:
    """(problems, notes). Problems: content or manifest drift, missing files and directories,
    and retired surfaces. Notes: the unowned paths in the adapter trees, which are not errors."""
    problems = [f"Missing directory: {d}" for d in sorted(expected.dirs) if not (root / d).is_dir()]
    for rel, out in sorted(expected.files.items()):
        path = root / rel
        if not path.is_file():
            problems.append(f"Missing file: {rel}")
            continue
        try:
            live = path.read_bytes()
        except OSError as exc:
            live = str(exc).encode()
        if live != out.data:
            diff = difflib.unified_diff(out.data.decode("utf-8", "replace").splitlines(keepends=True),
                                        live.decode("utf-8", "replace").splitlines(keepends=True),
                                        f"generated/{rel}", rel)
            head = (f"Manifest drift: {rel} does not list exactly the files sync generates; run "
                    "`make brain-sync` and commit the result" if rel == MANIFEST else f"Drift detected in {rel}")
            problems.append(f"{head}\n{''.join(diff)}")
    problems += [f"Obsolete Codex surface still exists: {d}/ -- {reason}" for d, reason in RETIRED_DIRS.items()
                 if (root / d).exists() or (root / d).is_symlink()]
    return problems, unowned(root, expected)


# --------------------------------------------------------------------------- check: lints
def canonical_names(directory: Path, bundles: bool = True) -> set[str]:
    """Flat `*.md` names (not README), plus `<n>/SKILL.md` bundles when `bundles`."""
    if not directory.is_dir():
        return set()
    return {e.stem if e.is_file() else e.name for e in directory.iterdir()
            if (e.is_file() and e.suffix == ".md" and e.name != "README.md")
            or (bundles and e.is_dir() and (e / "SKILL.md").is_file())}


def read_text(path: Path) -> str:
    """Decode a canonical file, raising BrainError (reported, not a traceback) if not UTF-8."""
    try:
        return path.read_bytes().decode("utf-8")
    except UnicodeDecodeError as exc:
        raise BrainError(f"{path} is not valid UTF-8 ({exc.reason} at byte {exc.start}).") from exc


def first_body_line(path: Path) -> str:
    """The first line that is not frontmatter, a heading, a horizontal rule, or blank."""
    in_frontmatter = False
    for i, raw in enumerate(read_text(path).splitlines()):
        line = raw.strip()
        if i == 0 and line == "---":
            in_frontmatter = True
        elif in_frontmatter:
            in_frontmatter = line != "---"
        elif line and not line.startswith("#") and line != "---":
            return line
    return ""


def lint_metadata(infra: Path) -> list[str]:
    """Every canonical agent and skill frontmatter (schema, name, length), and no copied first line."""
    entities, problems = load_entities(infra)
    for entity in entities.values():
        try:
            first = first_body_line(entity.path)
        except BrainError as exc:
            problems.append(str(exc))
            continue
        problems += [f"{entity.path.relative_to(infra.parent).as_posix()}: a description is byte-identical "
                     "to the first body line; write a distinct trigger-oriented summary."
                     for d in descriptions(entity.meta) if first and d.strip() == first]
    return problems


def lint_codex_agents(expected: Render) -> list[str]:
    """Every generated Codex agent wrapper parses as TOML with valid runtime keys."""
    problems: list[str] = []
    for rel, out in sorted(expected.files.items()):
        if not re.fullmatch(r"\.codex/agents/[^/]+\.toml", rel):
            continue
        try:
            data = tomllib.loads(out.data.decode("utf-8"))
        except (UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
            problems.append(f"{rel}: generated Codex agent TOML does not parse ({exc}).")
            continue
        problems += [f"{rel}: `{key}` must be a non-empty string."
                     for key in ("name", "description", "developer_instructions")
                     if not isinstance(data.get(key), str) or not data[key].strip()]
        if data.get("name") != Path(rel).stem:
            problems.append(f"{rel}: name {data.get('name')!r} does not match the filename.")
        if data.get("sandbox_mode") not in ENUMS["sandbox_mode"]:
            problems.append(f"{rel}: invalid or missing sandbox_mode {data.get('sandbox_mode')!r}.")
        if data.get("model_reasoning_effort", "low") not in ENUMS["reasoning_effort"]:
            problems.append(f"{rel}: invalid model_reasoning_effort; omit the key to inherit.")
        if "model" in data and (not isinstance(data["model"], str) or not data["model"].strip()):
            problems.append(f"{rel}: `model` is present but empty; omit the key to inherit.")
    return problems


def lint_frontmatter(infra: Path, expected: Render) -> list[str]:
    """Every generated frontmatter block parses as a YAML mapping and round-trips its canonical one."""
    try:
        import yaml  # PyYAML, a declared dependency of the check suite
    except ImportError:
        return ["PyYAML is required to parse generated frontmatter: pip install pyyaml"]
    entities = load_entities(infra)[0]

    def field_of(kind: str, key: str) -> dict[str, str]:
        return {name: e.meta[key] for (k, name), e in entities.items() if k == kind and key in e.meta}
    skill_desc, workflow_desc = field_of("skill", "description"), field_of("workflow", "description")
    hints = {**field_of("skill", "argument-hint"), **field_of("workflow", "argument-hint")}
    no_model = field_of("workflow", "disable-model-invocation")
    agent_hooks = field_of("agent", "hooks")
    workflows = {name for kind, name in entities if kind == "workflow"}
    surfaces = (  # (path pattern, descriptions, argument hints)
        (r"\.claude/agents/([^/]+)\.md", field_of("agent", "description"), {}),
        (r"\.claude/skills/([^/]+)/SKILL\.md", {**skill_desc, **workflow_desc}, hints),
        (r"\.agents/skills/([^/]+)/SKILL\.md", {**skill_desc, **workflow_desc}, {}),
    )
    problems: list[str] = []
    for pattern, descriptions, hints in surfaces:
        for rel, out in sorted(expected.files.items()):
            if not (match := re.fullmatch(pattern, rel)):
                continue
            entity, lines = match.group(1), out.data.decode("utf-8", "replace").splitlines()
            closing = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
            opened = bool(lines) and lines[0].strip() == "---"
            try:
                data = yaml.safe_load("\n".join(lines[1:closing])) if opened and closing else None
            except yaml.YAMLError as exc:
                problems.append(f"{rel}: frontmatter is not valid YAML ({' '.join(str(exc).split())}).")
                continue
            if not isinstance(data, dict):
                problems.append(f"{rel}: frontmatter is missing, unterminated, or not a YAML mapping.")
                continue
            if data.get("name") != entity:
                problems.append(f"{rel}: frontmatter name {data.get('name')!r} does not match `{entity}`.")
            if entity in descriptions and data.get("description") != descriptions[entity]:
                problems.append(f"{rel}: frontmatter description does not round-trip from its canonical file.")
            if entity in hints and data.get("argument-hint") != hints[entity]:
                problems.append(f"{rel}: argument-hint {data.get('argument-hint')!r} does not round-trip.")
            if rel.startswith(".claude/skills/") and entity in workflows \
                    and data.get("disable-model-invocation") != no_model.get(entity):
                problems.append(f"{rel}: disable-model-invocation does not round-trip from its canonical file.")
            if rel.startswith(".claude/agents/") and data.get("hooks") != (
                    claude_hooks(agent_hooks[entity]) if entity in agent_hooks else None):
                problems.append(f"{rel}: hooks do not round-trip from the canonical agent's `hooks:`.")
    return problems


def lint_invocation(root: Path, expected: Render | None) -> list[str]:
    """Canonical and Codex bodies carry no Claude syntax; argument bridges match the hints.

    Rules, templates, PROJECT.md, AGENTS.md, and AI_WORKFLOW.md are scanned with
    the workflow bodies, because both adapters read them and `/name` is not a command in Codex
    (AUTHORING.md section 8). A backticked `/name` fails for any workflow or dedicated style skill;
    a bare slash is left alone, since paths contain them."""
    infra = root / "Infrastructure"
    workflows = canonical_names(infra / "skills")
    problems = [f"'{n}' is both a workflow and a dedicated skill; keep one canonical body per name."
                for n in sorted(workflows & canonical_names(infra / "style" / "skills"))]
    invocable = workflows | canonical_names(infra / "style" / "skills")
    slash = re.compile(r"`/(" + "|".join(map(re.escape, sorted(invocable))) + r")(?=[`\s])")
    bodies = [(p.relative_to(root).as_posix(), read_text(p), "Canonical workflow body")
              for p in (infra / "skills" / n / "SKILL.md" for n in sorted(workflows)) if p.is_file()]
    shared = [infra / d / f"{n}.md" for d in ("rules", "templates") for n in sorted(canonical_names(infra / d))]
    bodies += [(p.relative_to(root).as_posix(), read_text(p), "Canonical file")
               for p in (*shared, root / "PROJECT.md", root / "AGENTS.md",
                         infra / "AI_WORKFLOW.md") if p.is_file()]
    bodies += [(rel, out.data.decode("utf-8", "replace"), "Codex skill")
               for rel, out in sorted((expected.files if expected else {}).items())
               if re.fullmatch(r"\.agents/skills/[^/]+/SKILL\.md", rel)]
    for rel, text, kind in bodies:
        if "$ARGUMENTS" in text:
            problems.append(f"{kind} {rel} contains the Claude-only `$ARGUMENTS` token.")
        problems += [f"{kind} {rel} uses Claude slash syntax `/{m.group(1)}`; name the workflow without "
                     "the slash." for m in (slash.finditer(text) if invocable else ())]
    hinted = {name for (kind, name), e in load_entities(infra)[0].items()
              if kind == "workflow" and "argument-hint" in e.meta}
    for name in sorted(workflows):
        skill = expected.files.get(f".claude/skills/{name}/SKILL.md") if expected else None
        if skill is not None and (name in hinted) != (b"Arguments: $ARGUMENTS" in skill.data):
            problems.append(f".claude/skills/{name}/SKILL.md: the `Arguments: $ARGUMENTS` bridge must be "
                            "present exactly when the workflow's frontmatter declares an argument-hint.")
    return problems


AGENTS_MD_CAP = 32 * 1024  # Codex project_doc_max_bytes default; past it the file is truncated
IMPORT_LINE = re.compile(r"^@\S", re.MULTILINE)


def root_instruction_problems(root: Path) -> list[str]:
    """The hand-written root files: AGENTS.md is the shared body, and CLAUDE.md imports it.

    Codex reads AGENTS.md verbatim (no imports, 32 KiB cap), so it must be self-contained.
    Claude reads CLAUDE.md, which expands `@AGENTS.md` at launch and adds Claude-only notes.
    """
    agents, claude = root / "AGENTS.md", root / "CLAUDE.md"
    problems = [f"Missing root instruction file: {p.name} (written by hand; brain.py does not generate it)."
                for p in (agents, claude) if not p.is_file()]
    if (root / "Infrastructure" / "root_instructions").exists():
        problems.append("Infrastructure/root_instructions/ is retired: AGENTS.md and CLAUDE.md are edited in "
                        "place, and the adapter README sources live in Infrastructure/adapter_configs/.")
    if agents.is_file():
        text = read_text(agents)
        if len(text.encode()) > AGENTS_MD_CAP:
            problems.append(f"AGENTS.md is {len(text.encode())} bytes; Codex truncates past {AGENTS_MD_CAP}.")
        if IMPORT_LINE.search(text):
            problems.append("AGENTS.md has an `@path` import line; Codex has no imports, so keep it self-contained.")
    if claude.is_file():
        text = read_text(claude)
        if "@AGENTS.md" not in text.splitlines():
            problems.append("CLAUDE.md must import the shared instructions with an `@AGENTS.md` line.")
        if "Codex" in text:
            problems.append("CLAUDE.md mentions Codex; shared text belongs in AGENTS.md.")
    return problems


def lint_canonical(root: Path) -> list[str]:
    """Only declared canonical duplication, and the root-instruction contract."""
    infra, problems = root / "Infrastructure", []
    locations: dict[str, list[str]] = {}
    for label in CANONICAL_LOCATIONS:
        for name in canonical_names(infra / label):
            locations.setdefault(name, []).append(label)
    problems += [f"Unapproved canonical duplication: '{name}' appears in {', '.join(sorted(where))}. Rename "
                 "one, or declare it in ALLOWED_DUPLICATIONS in brain.py with the reason."
                 for name, where in sorted(locations.items())
                 if len(where) > 1 and (tuple(sorted(where)), name) not in ALLOWED_DUPLICATIONS]
    problems += root_instruction_problems(root)
    return problems


# --------------------------------------------------------------------------- check: load
# The words every Claude session and subagent loads before its first turn: CLAUDE.md with its
# `@path` imports expanded (AGENTS.md) and every `load: always` rule as mirrored. The ceiling
# is the Phase 2 Stage D measurement and only moves down: lower it in the commit that cuts
# words (target 1,500 after Phase 3A). Raising it needs the owner's approval. The owner approved
# 1,246 -> 1,261 on 2026-09-30 for the literature-store carve-out in AGENTS.md (plans, verification),
# and 1,261 -> 1,339 on 2026-10-01 for the EIG AI-use guardrail in AGENTS.md.
ALWAYS_LOADED_CEILING = 1339
# Guardrails AGENTS.md must keep, because a shrinking word budget invites cuts. Each is one or
# more phrases, matched case-insensitively with whitespace collapsed. Phrases, not comment
# markers: a marker can outlive the sentence it labels, while a phrase fails as soon as the
# guardrail is deleted or reworded, so a rewording updates this table in the same commit, in
# front of the reviewer. AGENTS.md, not CLAUDE.md, because Codex reads only AGENTS.md.
REQUIRED_ANCHORS = {
    "no fabrication": ("do not fabricate data, citations, or results",),
    "project-framing exception": ("project-framing exception",),
    "non-interactive blocker": ("report a blocker to your caller",),
    "generated-file rule": ("do not hand-edit generated copies",),
    "commit attribution": ("configured git user", "do not add ai co-author trailers"),
    "ai drafts no work-product prose": ("never draft any part of an eig work product's prose",
                                        "records/ai-use-log.md"),
}
LOADING_MAP = ("Infrastructure/TEMPLATE_CENSUS.md", "<!-- loading-map:begin -->", "<!-- loading-map:end -->")
FIXED_TIERS = (  # file type -> (tier, Claude, Codex); AUTHORING.md section 1 fixes these by type
    ("`Infrastructure/agents/<name>.md`", "invoked", "when spawned (`.claude/agents/`); description always listed",
     "when spawned (`.codex/agents/<name>.toml`)"),
    ("`Infrastructure/skills/<name>/SKILL.md`", "invoked", "when invoked (`.claude/skills/`); description "
     "always listed", "when invoked (`.agents/skills/`); description always listed"),
    ("`Infrastructure/style/skills/<name>`", "invoked", "when invoked (`.claude/skills/`); description always "
     "listed", "when invoked (`.agents/skills/`); description always listed"),
    ("`PROJECT.md`, `Infrastructure/AI_WORKFLOW.md`", "referenced",
     "read by path at startup (`AGENTS.md`)", "read by path at startup (`AGENTS.md`)"),
    ("`Infrastructure/templates/<name>`, `Infrastructure/style/docs/<name>`", "referenced", "read by path",
     "read by path"),
)


def words(text: str) -> int:
    """Whitespace-separated words, as `wc -w` counts them."""
    return len(text.split())


def expand_imports(root: Path, rel: str, hops: int = 4) -> list[tuple[str, int]]:
    """(file, words) for a CLAUDE.md-style file and each `@path` it imports, at most `hops` deep."""
    text = read_text(root / rel)
    own = [line for line in text.splitlines() if not IMPORT_LINE.match(line)]
    found = [(rel, words("\n".join(own)))]
    for line in text.splitlines():
        target = posixpath.normpath(posixpath.join(posixpath.dirname(rel), line[1:].strip()))
        if IMPORT_LINE.match(line) and hops and (root / target).is_file():
            found += expand_imports(root, target, hops - 1)
    return found


def always_loaded(root: Path, expected: Render) -> list[tuple[str, int]]:
    """(file, words) for everything a Claude session loads at start."""
    entities = load_entities(root / "Infrastructure")[0]
    rules = sorted(name for (kind, name), e in entities.items() if kind == "rule" and e.meta.get("load") == "always")
    return expand_imports(root, "CLAUDE.md") + [
        (f"Infrastructure/rules/{name}.md", words(expected.files[f".claude/rules/{name}.md"].data.decode("utf-8")))
        for name in rules]


def loading_map(root: Path) -> str:
    """The loading-map table: root files and every rule by file, other instruction files by type."""
    entities = load_entities(root / "Infrastructure")[0]
    order = {"always": 0, "paths": 1, "referenced": 2}
    rows = [("`CLAUDE.md`", "always", "every session and subagent", "not read"),
            ("`AGENTS.md`", "always", "every session and subagent (imported by `CLAUDE.md`)", "every session")]
    for name, meta in sorted(((n, e.meta) for (k, n), e in entities.items() if k == "rule"),
                             key=lambda item: (order.get(item[1].get("load"), 3), item[0])):
        load = meta.get("load")
        claude = {"always": "every session and subagent (`.claude/rules/`)",
                  "paths": "when a matching file is read: " + ", ".join(f"`{g}`" for g in meta.get("paths", []))
                  }.get(load, "read by path")
        rows.append((f"`Infrastructure/rules/{name}.md`", str(load), claude, "read by path"))
    rows += list(FIXED_TIERS)
    lines = ["| File | `load` | Claude Code | Codex |", "|---|---|---|---|"]
    return "\n".join(lines + [f"| {' | '.join(row)} |" for row in rows]) + "\n"


def committed_map(root: Path) -> tuple[str | None, str]:
    """(the table between the markers in the census, or None, and the whole census text)."""
    path, begin, end = LOADING_MAP
    text = read_text(root / path) if (root / path).is_file() else ""
    start, stop = text.find(begin + "\n"), text.find(end)
    return (text[start + len(begin) + 1:stop] if 0 <= start < stop else None), text


def check_load(root: Path, expected: Render) -> tuple[list[str], str]:
    """(problems, summary): the always-loaded ceiling, the required anchors, and the loading map."""
    loaded = always_loaded(root, expected)
    total = sum(n for _, n in loaded)
    problems = [f"{total:,} words load in every Claude session, above the ceiling of {ALWAYS_LOADED_CEILING:,} "
                "(ALWAYS_LOADED_CEILING in brain.py). Cut always-loaded text, or move a rule to `load: paths` or "
                "`load: referenced`; raise the ceiling only with the owner's approval."] \
        if total > ALWAYS_LOADED_CEILING else []
    agents = " ".join(read_text(root / "AGENTS.md").split()).casefold() if (root / "AGENTS.md").is_file() else ""
    problems += [f"AGENTS.md no longer states the {name} guardrail (missing phrase: \"{phrase}\"). Restore it; if "
                 "you reworded it on purpose, update REQUIRED_ANCHORS in brain.py in the same commit."
                 for name, phrases in REQUIRED_ANCHORS.items() for phrase in phrases if phrase not in agents]
    table, _ = committed_map(root)
    if table != loading_map(root):
        problems.append(f"The loading map in {LOADING_MAP[0]} is {'missing' if table is None else 'out of date'}; "
                        "run `python3 Infrastructure/scripts/brain.py loading-map --write` and commit the result.")
    listed = sum(words(d) for (kind, _), e in load_entities(root / "Infrastructure")[0].items()
                 if kind != "rule" for d in descriptions(e.meta)[:1])
    parts = ", ".join(f"{rel} {n:,}" for rel, n in loaded)
    return problems, (f"{total:,} always-loaded words (ceiling {ALWAYS_LOADED_CEILING:,}): {parts}. Not budgeted: "
                      f"{listed:,} words of agent and skill descriptions in the listings.")


def write_loading_map(root: Path) -> int:
    table, text = committed_map(root)
    if table is None:
        print(f"brain.py: {LOADING_MAP[0]} has no `{LOADING_MAP[1]}` / `{LOADING_MAP[2]}` block to fill.",
              file=sys.stderr)
        return 1
    start = text.find(LOADING_MAP[1] + "\n") + len(LOADING_MAP[1]) + 1
    (root / LOADING_MAP[0]).write_text(text[:start] + loading_map(root) + text[start + len(table):], encoding="utf-8", newline="\n")
    print(f"Wrote the loading map into {LOADING_MAP[0]}.")
    return 0


# --------------------------------------------------------------------------- check: driver
PARTS = ("drift", "lints", "load", "suites")
SUITES = (("hook-tests", "test_hooks.py"), ("brain-tests", "test_brain.py"))
SUITE_TIMEOUT = 300  # seconds per suite


def report(step: str, problems: list[str], passed: str) -> bool:
    if problems:
        print(f"[{step}] FAIL: {len(problems)} problem(s)", file=sys.stderr)
        print("".join(f"- {problem}\n" for problem in problems), end="", file=sys.stderr)
        return False
    print(f"[{step}] PASS: {passed}")
    return True


def check(root: Path, parts: list[str]) -> int:
    """Run the selected parts; each part runs even when an earlier one failed."""
    expected: Render | None = None
    generation: list[str] = []
    try:
        expected = render(root)
    except BrainError as exc:
        generation = [f"Generation failed: {exc}"]
    ok = True
    if "drift" in parts:
        problems, notes = (generation, []) if generation else check_drift(root, expected)  # type: ignore[arg-type]
        ok &= report("drift", problems, f"{len(expected.files) if expected else 0} generated files match "
                     f"their canonical sources and {MANIFEST}; no missing files or retired paths.")
        if notes:
            print(f"[drift] INFO: {len(notes)} unowned path(s) in .claude/, .codex/, or .agents/. Sync "
                  f"does not generate them and never touches them:\n{listing(notes)}", end="")
    if "lints" in parts:
        infra = root / "Infrastructure"
        problems = [] if "drift" in parts else list(generation)
        lints = [lambda: lint_metadata(infra), lambda: lint_invocation(root, expected),
                 lambda: lint_canonical(root)]
        if expected is not None:
            lints += [lambda: lint_codex_agents(expected), lambda: lint_frontmatter(infra, expected)]
        for lint in lints:
            try:
                problems += lint()
            except BrainError as exc:
                problems.append(str(exc))
        ok &= report("lints", problems, "canonical frontmatter, generated TOML and frontmatter, "
                     "invocation hygiene, and declared canonical duplication.")
    if "load" in parts:
        try:
            problems, summary = (list(generation), "") if generation else check_load(root, expected)  # type: ignore[arg-type]
        except BrainError as exc:
            problems, summary = [str(exc)], ""
        if problems and summary:
            print(f"[load] INFO: {summary}", file=sys.stderr)
        ok &= report("load", problems, f"{summary} {len(REQUIRED_ANCHORS)} required anchors present in "
                     "AGENTS.md; loading map current.")
    for step, script in SUITES if "suites" in parts else ():
        try:
            result = subprocess.run([sys.executable, str(root / "Infrastructure" / "scripts" / script)],
                                    cwd=root, capture_output=True, text=True, timeout=SUITE_TIMEOUT, check=False)
        except subprocess.TimeoutExpired:
            ok &= report(step, [f"{script} timed out after {SUITE_TIMEOUT}s."], "")
            continue
        detail = (result.stdout + result.stderr).strip()
        ok &= report(step, [detail] if result.returncode else [], detail.splitlines()[-1] if detail else script)
    return 0 if ok else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate and check the adapter trees.", allow_abbrev=False)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("sync", allow_abbrev=False, help="regenerate the adapter files")
    commands.add_parser("check", allow_abbrev=False, help="report drift, lints, load, and suites").add_argument(
        "--only", action="append", choices=PARTS, help="run only this part (repeatable)")
    commands.add_parser("loading-map", allow_abbrev=False, help="print the loading map").add_argument(
        "--write", action="store_true", help=f"write it into {LOADING_MAP[0]} instead")
    args = parser.parse_args(argv)
    try:
        if args.command == "sync":
            return sync(ROOT)
        if args.command == "loading-map":
            return write_loading_map(ROOT) if args.write else print(loading_map(ROOT), end="") or 0
        return check(ROOT, args.only or list(PARTS))
    except BrainError as exc:
        print(f"brain.py: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
