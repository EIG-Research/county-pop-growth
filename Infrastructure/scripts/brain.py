#!/usr/bin/env python3
"""Generate and check every adapter file from the canonical Infrastructure/ sources.

    brain.py sync                                   regenerate the adapter files
    brain.py check [--only drift|lints|suites]...   report problems; exit 1 on any

This began (Phase 2 Stage A) as a byte-for-byte port of the retired Bash generator, and
`check` took over the three retired structural checkers. A parity proof (`test_brain.py
--parity`) showed identical output, apart from deliberate differences on pathological input,
before they were removed. Behavior kept only to match the Bash output is marked "Parity:".

Ownership is by manifest (Phase 2 Stage C1). Sync records every file it generates in the
committed MANIFEST, writes only those files, and deletes a path only when the previous
manifest listed it, it lies inside an adapter tree, and it is no longer generated. Any other
file under .claude/, .codex/, or .agents/ -- a user's own agent, skill, or
settings.local.json -- is never touched; `check` lists it as information. A hand-edited
generated file is still owned: `check` reports it as drift and the next sync overwrites it.
The guard hook reads the same manifest, so it blocks edits to exactly these files.

Agent, skill, and rule metadata lives in YAML frontmatter at the top of each canonical file
(Phase 2 Stages B and D; SCHEMAS below). It is parsed with PyYAML and stripped from the body
before generation. A missing required key, an unknown key, or an invalid value is an error;
there are no defaults. A rule's `load:` key sets its tier: `always` and `paths` rules are
mirrored into .claude/rules/ (with only `paths:` kept), and `referenced` rules are read by path.

One command policy, adapter_configs/permissions.yaml (Phase 2 Stage E), renders Claude's
`permissions` into .claude/settings.json and the whole Codex execpolicy, so drift in either
is ordinary generated-file drift.

`check --only load` (Phase 2 Stage D) measures the words every Claude session loads against
ALWAYS_LOADED_CEILING, requires the REQUIRED_ANCHORS in AGENTS.md, and compares the loading
map in TEMPLATE_CENSUS.md with the one computed here (`brain.py loading-map [--write]`).
"""

